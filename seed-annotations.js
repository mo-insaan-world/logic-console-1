// Single source of truth for atom-extraction granularity: read the prompt
// constant out of the shared Deno TS module via regex parse. This keeps the
// seeder, parse-actions (browser-facing), and scoring.ts (harness) on the
// exact same prompt — any divergence introduces extraction asymmetry into
// W_c. The .ts module is imported normally in Deno; Node falls back to
// reading the file at startup.
function loadSharedExtractionPrompt() {
  const file = path.join(__dirname, 'supabase/functions/_shared/extraction-prompt.ts');
  const src = fs.readFileSync(file, 'utf8');
  const m = src.match(/export const EXTRACTION_SYSTEM_PROMPT\s*=\s*`([\s\S]*?)`;/);
  if (!m) throw new Error('Could not parse EXTRACTION_SYSTEM_PROMPT from ' + file);
  return m[1];
}
