function buildCasePrompt(c, decision, annotationNumber) {
  const labelled = {};
  Object.entries(c.constraints).forEach(([k, level]) => {
    labelled[k] = (constraintMeta[k] && constraintMeta[k][level]) || level;
  });

  const decisionInstruction = {
    definitive: `Your tactical decision is DEFINITIVE REPAIR. In action_trace, describe the operative sequence you performed, including pathways you ruled out. In reasoning_trace, explain your clinical logic for definitive repair given the active resource constraints, and why you ruled out alternative surgical pathways.`,
    damage:     `Your tactical decision is DAMAGE CONTROL. In action_trace, describe the abbreviated/staged steps you took and what you deferred. In reasoning_trace, explain why an abbreviated operation rather than definitive repair, and the specific physiological endpoint you are waiting for before returning to theatre.`,
    transfer:   `Your tactical decision is TRANSFER OR TEMPORISE. In action_trace, describe the bridge actions you took and the handoff itself. In reasoning_trace, explain why local intervention is not viable for this patient, and the clinical trade-off or risk if the handoff is delayed.`,
  }[decision];

  const jsonStructure = `{
  "action_trace": "Sequence of discrete clinical actions taken, including ones ruled out. 3-8 sentences.",
  "reasoning_trace": "Why this approach given the active constraints. IF/THEN logic preferred.",
  "predicted_outcome": "Expected clinical result with and without this approach."
}`;

  return `Case ID: ${c.id}
Difficulty: ${c.difficulty_rating}

SCENARIO:
History: ${c.scenario.history}
Examination: ${c.scenario.examination}
Working Diagnosis: ${c.scenario.working_diagnosis}

VITALS: HR ${c.vitals.hr} bpm, BP ${c.vitals.bp_s}/${c.vitals.bp_d} mmHg, GCS ${c.vitals.gcs}/15, SpO2 ${c.vitals.spo2}%, Lactate ${c.vitals.abg.lactate}, pH ${c.vitals.abg.ph}, BE ${c.vitals.abg.be}

CONSTRAINTS (current resource availability):
${Object.entries(labelled).map(([k,v]) => `  ${k}: ${v}`).join('\n')}

TASK: ${decisionInstruction}
This is annotation ${annotationNumber} of 3 for this case — vary your wording and emphasis from the other annotations, but stay on the same tactical decision.

Respond ONLY with this exact JSON structure (no preamble, no markdown):
${jsonStructure}`;
}

async function generateAnnotation(c, decision, annotationNumber) {
  const systemPrompt = `You are a senior trauma surgeon with 15 years experience at a major urban trauma centre. Generate a realistic clinical annotation for the following case. Your reasoning should reflect genuine surgical judgment — acknowledge the constraints, explain your decision pathway, and be specific about why you chose definitive repair, damage control, or transfer/temporise. Write as if dictating to a registrar. Be concise but clinically precise. Respond only in JSON.`;

  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type':    'application/json',
      'x-api-key':       ANTHROPIC_KEY,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model:      'claude-sonnet-4-6',
      max_tokens: 1500,
      system:     systemPrompt,
      messages: [{ role: 'user', content: buildCasePrompt(c, decision, annotationNumber) }],
    }),
  });

  if (!res.ok) throw new Error('Anthropic error ' + res.status + ': ' + await res.text());
  const data = await res.json();
  if (data.stop_reason === 'max_tokens') throw new Error('Response truncated — increase max_tokens');
  const raw = data.content[0].text.trim();
  // strip markdown code fences if present
  const stripped = raw.replace(/^```(?:json)?\s*/,'').replace(/\s*```$/,'');
  const match = stripped.match(/\{[\s\S]*\}/);
  if (!match) throw new Error('No JSON in response:\n' + raw);
  return JSON.parse(match[0]);
}

// Extracts atomic actions from a generated action_trace using the SHARED
// extraction prompt — same prompt parse-actions and scoring.ts use. Produces
// 6–10 intent-driven tactical maneuvers (per the granularity rules in the
// shared prompt). Synthetic rows store the result as both action_atoms_proposed
// and action_atoms_confirmed since there is no surgeon to edit between them.
async function extractAtomsViaSharedPrompt(actionTrace) {
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'Content-Type':'application/json', 'x-api-key':ANTHROPIC_KEY, 'anthropic-version':'2023-06-01' },
    body: JSON.stringify({
      model:      'claude-sonnet-4-6',
      max_tokens: 1000,
      system:     EXTRACTION_SYSTEM_PROMPT,
      messages:   [{ role: 'user', content: `Extract atomic actions from this trace:\n"${actionTrace}"` }],
    }),
  });
  if (!res.ok) throw new Error('Atom extraction failed: ' + await res.text());
  const data = await res.json();
  const raw = (data.content[0].text || '').trim();
  const stripped = raw.replace(/^```(?:json)?\s*/, '').replace(/\s*```$/, '');
  const parsed = JSON.parse(stripped);
  if (!Array.isArray(parsed)) throw new Error('Parser did not return a JSON array: ' + raw);
  return parsed.filter(s => typeof s === 'string' && s.trim().length > 0);
}

async function generateLethalCritique(c, stepText) {
  const labelled = {};
  Object.entries(c.constraints).forEach(([k, level]) => {
    labelled[k] = (constraintMeta[k] && constraintMeta[k][level]) || level;
  });
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'Content-Type':'application/json', 'x-api-key':ANTHROPIC_KEY, 'anthropic-version':'2023-06-01' },
    body: JSON.stringify({
      model: 'claude-sonnet-4-6',
      max_tokens: 200,
      system: 'You are a trauma surgeon explaining why a specific textbook step would be fatal under the active resource constraints. Respond with one concise clinical sentence (20-40 words). No preamble.',
      messages: [{ role:'user', content:`Active constraints:\n${Object.entries(labelled).map(([k,v])=>`  ${k}: ${v}`).join('\n')}\n\nTextbook step flagged LETHAL:\n"${stepText}"\n\nWhy is this step lethal under these constraints?` }]
    }),
  });
  if (!res.ok) throw new Error('Critique gen failed: ' + await res.text());
  const data = await res.json();
  return data.content[0].text.trim();
}

function resilienceScore(decision, constraints) {
  const failing = Object.values(constraints).filter(v => v > 0).length;
  const base = decision === 'definitive' ? 80 : decision === 'damage' ? 65 : 50;
  const jitter = Math.floor(Math.random() * 12) - 6;
  return Math.max(30, Math.min(98, base - failing * 2 + jitter));
}

function timeToDecision(decision) {
  const ranges = { definitive: [450,650], damage: [220,450], transfer: [180,380] };
  const [lo, hi] = ranges[decision];
  return lo + Math.floor(Math.random() * (hi - lo));
}

function keyVitals(c) {
  const v = c.vitals;
  const keys = [];
  if (v.hr_crit)  keys.push('HR ' + v.hr + ' bpm [CRITICAL]');
  if (v.bp_crit)  keys.push('BP ' + v.bp_s + '/' + v.bp_d + ' mmHg [CRITICAL]');
  if (v.rr_crit)  keys.push('RR ' + v.rr + ' [CRITICAL]');
  if (v.abg) {
    if (v.abg.lactate >= 2) keys.push('Lactate ' + v.abg.lactate);
    if (v.abg.be <= -3)     keys.push('BE ' + v.abg.be);
    if (v.abg.ph < 7.35)    keys.push('pH ' + v.abg.ph);
  }
  return keys;
}

async function insertSubmission(caseId, decision, reasoningJson, atoms, resScore, timeS, constraintSnap) {
  // Slice 3: writes the full five-field hybrid reasoning_json shape so seeded
  // rows are indistinguishable from live consultant submissions to any
  // downstream reader. action_atoms_proposed === action_atoms_confirmed and
  // atoms_edited=false because synthetic rows have no surgeon to edit between
  // the proposed and confirmed sets.
  const body = {
    case_id:                  caseId,
    view_mode:                'consultant',
    decision:                 null,
    reasoning_json: {
      action_trace_raw:       reasoningJson.action_trace,
      action_atoms_proposed:  atoms,
      action_atoms_confirmed: atoms,
      atoms_edited:           false,
      reasoning_trace:        reasoningJson.reasoning_trace,
    },
    resilience_score:         resScore,
    constraint_snapshot:      constraintSnap,
    time_to_decision_seconds: timeS,
  };

  const res = await fetch(SUPABASE_URL + '/rest/v1/submissions', {
    method: 'POST',
    headers: sbHeaders(),
    body: JSON.stringify(body),
  });
  if (!res.ok) throw new Error('Insert failed: ' + await res.text());
  return res.json();
}

async function patchPhase2(submissionId, c, perStepRatings) {
  const steps = c.static_textbook_protocol || c.ai_steps || [];
  const ratings = [];
  for (let i = 0; i < steps.length; i++) {
    const rating = perStepRatings[i] || 'acceptable';
    const obj = { step_index: i + 1, step_text: steps[i], rating, rated_at: new Date().toISOString() };
    if (rating === 'lethal') {
      obj.critique = await generateLethalCritique(c, steps[i]);
      await new Promise(r => setTimeout(r, 300));
    }
    ratings.push(obj);
  }
  const hasLethal = ratings.some(r => r.rating === 'lethal');
  const hasSubOpt = ratings.some(r => r.rating === 'sub_optimal');
  const aiSafetyRating = hasLethal ? 'LETHAL' : hasSubOpt ? 'SUB-OPTIMAL' : 'ACCEPTABLE';
  const lethalCritiques = ratings.filter(r => r.rating === 'lethal' && r.critique).map(r => 'Step ' + r.step_index + ': ' + r.critique).join('\n');

  const phase2Body = {
    phase2_step_ratings_json: { ratings },
    ai_safety_rating: aiSafetyRating,
    adversarial_critique_trace: lethalCritiques || null,
    standard_of_care_steps: steps,
    phase2_completed_at: new Date().toISOString(),
  };
  const res = await fetch(SUPABASE_URL + '/rest/v1/submissions?id=eq.' + submissionId, {
    method: 'PATCH',
    headers: Object.assign(sbHeaders(), { 'Prefer': 'return=minimal' }),
    body: JSON.stringify(phase2Body),
  });
  if (!res.ok) throw new Error('Phase 2 PATCH failed: ' + await res.text());
  return aiSafetyRating;
}

