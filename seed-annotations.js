function isGarbage(rj) {
  if (!rj || typeof rj !== 'object') return false;
  const vals = Object.values(rj).filter(v => typeof v === 'string');
  return vals.some(v => {
    const trimmed = v.trim();
    // single word (no spaces) and under 5 characters
    return trimmed.length < 5 && !/\s/.test(trimmed);
  });
}

